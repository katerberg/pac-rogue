export function parseMazeParam(params: URLSearchParams): MazeLayoutId | null {
  const raw = params.get("maze");
  if (raw === null || raw === "") {
    return null;
  }
  if (raw === "maze1" || raw === "maze2" || raw === "mazeSmall" || raw === "mazeLarge") {
    return raw;
  }
  return null;
}

export function pickLayoutId(
  rng: () => number = Math.random,
  override: MazeLayoutId | null = null,
): MazeLayoutId {
  if (override !== null) {
    return override;
  }
  return rng() < 0.5 ? "maze1" : "maze2";
}
